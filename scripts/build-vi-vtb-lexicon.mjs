#!/usr/bin/env node
/**
 * Compiles a compact, Cloudflare Worker-safe Vietnamese word frequency & POS lexicon
 * from UniversalDependencies/UD_Vietnamese-VTB (CC BY-SA 4.0).
 *
 * Output: functions-src/data/vi-vtb-lexicon.js
 * Usage:  node scripts/build-vi-vtb-lexicon.mjs
 */

import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = resolve(__dirname, '../functions-src/data/vi-vtb-lexicon.js');

const VTB_URLS = [
    'https://raw.githubusercontent.com/UniversalDependencies/UD_Vietnamese-VTB/master/vi_vtb-ud-train.conllu',
    'https://raw.githubusercontent.com/UniversalDependencies/UD_Vietnamese-VTB/master/vi_vtb-ud-dev.conllu',
    'https://raw.githubusercontent.com/UniversalDependencies/UD_Vietnamese-VTB/master/vi_vtb-ud-test.conllu'
];

const VALID_VI_WORD_RE = /^[a-zàáâãèéêìíòóôõùúýăđĩũơưạảấầẩẫậắằẳẵặẹẻẽếềểễệỉịọỏốồổỗộớờởỡợụủứừửữựỳỵỷỹ]+(?: [a-zàáâãèéêìíòóôõùúýăđĩũơưạảấầẩẫậắằẳẵặẹẻẽếềểễệỉịọỏốồổỗộớờởỡợụủứừửữựỳỵỷỹ]+){0,3}$/u;

const UPOS_TO_LABEL = {
    NOUN: 'Noun',
    PROPN: 'Noun',
    VERB: 'Verb',
    ADJ: 'Adjective',
    ADV: 'Adverb',
    PRON: 'Pronoun',
    DET: 'Determiner',
    ADP: 'Preposition',
    CCONJ: 'Conjunction',
    SCONJ: 'Conjunction',
    AUX: 'Auxiliary',
    PART: 'Particle',
    INTJ: 'Interjection',
    NUM: 'Numeral'
};

function mapTag(upos, xpos) {
    if (xpos === 'Nc') return 'Classifier';
    return UPOS_TO_LABEL[upos] || null;
}

async function main() {
    const wordStats = new Map(); // word -> { total, propn, posCounts: Map<string, number> }

    for (const url of VTB_URLS) {
        console.log(`Fetching ${url}...`);
        const res = await fetch(url, { signal: AbortSignal.timeout(30000) });
        if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${url}`);
        const text = await res.text();

        for (const line of text.split(/\r?\n/)) {
            if (!line || line.startsWith('#')) continue;
            const cols = line.split('\t');
            if (cols.length < 5 || cols[0].includes('-') || cols[0].includes('.')) continue;

            const rawForm = cols[1].normalize('NFC').toLowerCase().replace(/\s+/g, ' ').trim();
            const upos = cols[3];
            const xpos = cols[4];

            if (!VALID_VI_WORD_RE.test(rawForm)) continue;
            const label = mapTag(upos, xpos);
            if (!label) continue;

            let stat = wordStats.get(rawForm);
            if (!stat) {
                stat = { total: 0, propn: 0, posCounts: new Map() };
                wordStats.set(rawForm, stat);
            }
            stat.total++;
            if (upos === 'PROPN') stat.propn++;
            stat.posCounts.set(label, (stat.posCounts.get(label) || 0) + 1);
        }
    }

    const entries = {};
    let kept = 0;
    let compoundCount = 0;

    const sortedWords = Array.from(wordStats.keys()).sort();
    for (const word of sortedWords) {
        const stat = wordStats.get(word);
        // Skip rare pure proper-noun entries (noise names that appear only once or twice)
        if (stat.propn === stat.total && stat.total < 3) continue;

        const rankedPos = Array.from(stat.posCounts.entries())
            .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));

        const primaryPos = rankedPos[0][0];
        const secondaryPos = rankedPos[1] && rankedPos[1][1] >= Math.max(2, stat.total * 0.2)
            ? rankedPos[1][0]
            : null;

        entries[word] = secondaryPos
            ? [stat.total, primaryPos, secondaryPos]
            : [stat.total, primaryPos];

        kept++;
        if (word.includes(' ')) compoundCount++;
    }

    const banner = [
        '/**',
        ' * Compiled Vietnamese word frequency & POS lexicon.',
        ' * Source: UniversalDependencies/UD_Vietnamese-VTB (CC BY-SA 4.0)',
        ' * https://github.com/UniversalDependencies/UD_Vietnamese-VTB',
        ` * Entries: ${kept} (${compoundCount} multi-syllable compounds)`,
        ' * Generated by: scripts/build-vi-vtb-lexicon.mjs',
        ' */',
        ''
    ].join('\n');

    const output = `${banner}export const VI_VTB_LEXICON = ${JSON.stringify(entries)};\n`;
    await mkdir(dirname(OUTPUT_PATH), { recursive: true });
    await writeFile(OUTPUT_PATH, output, 'utf8');
    console.log(`Wrote ${kept} entries (${compoundCount} compounds, ${(Buffer.byteLength(output) / 1024).toFixed(1)} KB) to ${OUTPUT_PATH}`);
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
