function translateTitle(title, targetLang) {
  if (!title) return '';
  const dict = TITLE_ANNOTATIONS[targetLang];
  if (!dict) return title;

  let result = title;
  for (const [en, localized] of Object.entries(dict)) {
    const regex = new RegExp(`\\b${escapeRegExp(en)}\\b`, 'gi');
    result = result.replace(regex, localized);
  }
  return result;
}

function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

