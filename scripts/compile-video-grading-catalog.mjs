import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const source = process.argv[2];
if (!source) throw new Error('Pass the Flutter assets/grammar directory');
const read = async path => JSON.parse(await readFile(resolve(source, path), 'utf8'));
const catalog = {};
for (const lang of ['ja', 'zh', 'ko', 'en']) {
    const patterns = await read(`grammar_${lang}.json`);
    const index = await read(`index/grammar_index_${lang}.json`);
    const ids = Object.fromEntries(patterns.map(({ id, level, formation, pattern, title }) =>
        [id, [level, /^(verb|adjective)/i.test(formation), /^verb/i.test(pattern) || /^verb/i.test(title)]]));
    // Match Flutter's handling of index entries whose pattern was removed.
    const byId = id => ids[id];
    const known = list => list.filter(item => Object.hasOwn(ids, item.patternId));
    catalog[lang] = {
        sequences: Object.fromEntries(Object.entries(index.sequences)
            .map(([key, matches]) => [key, byId(matches.find(id => Object.hasOwn(ids, id)))])
            .filter(([, pattern]) => pattern)),
        endings: known(index.verbEndings).map(p => [p.suffix, byId(p.patternId)]).sort((a, b) => b[0].length - a[0].length),
        auxiliaries: known(index.auxPhrases).map(p => [p.connective, p.auxStem, byId(p.patternId)]),
        correlatives: known(index.correlatives).map(p => [p.head, p.tail, byId(p.patternId)]),
        templates: known(index.templates).reduce((templates, p) => {
            (templates[p.anchor] ??= []).push({ ...p, pattern: byId(p.patternId) });
            return templates;
        }, Object.create(null)),
        stoplist: index.singleCharStoplist
    };
}
const output = new URL('../functions-src/data/video-grading-catalog.mjs', import.meta.url);
const generated = '// Generated by scripts/compile-video-grading-catalog.mjs.\nexport default ' + JSON.stringify(catalog) + ';\n';
if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== generated) throw new Error('Regenerate the grading catalog and review the grader version');
} else {
    await writeFile(output, generated);
}
